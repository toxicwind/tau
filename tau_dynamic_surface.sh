#!/usr/bin/env bash
set -uo pipefail
TAU="$HOME/estate/ranch/tau"
BIN="$HOME/.local/bin/tau"
STAMP=$(date +%Y%m%d_%H%M%S)

echo "═══ 1. FIND loadManifests ACROSS THE WHOLE TREE ═══"
HITS=$(grep -rln 'loadManifests' "$TAU" 2>/dev/null | grep -v node_modules | grep -v '.bak.' || true)
if [ -z "$HITS" ]; then
  echo "  FAIL: no file defines loadManifests"
  echo "  searching for surface/ dir too:"
  find "$TAU" -type d -name surface -not -path '*/node_modules/*' 2>/dev/null | sed 's|^|    |'
  exit 1
fi
printf '  hits:\n'; printf '%s\n' "$HITS" | sed 's|^|    |'
MACRO=$(printf '%s\n' "$HITS" | head -1)
MACRO_DIR="$(dirname "$MACRO")"
SURF_DIR="$MACRO_DIR/surface"
echo "  macro: $MACRO"
echo "  surface dir: $SURF_DIR"
ls "$SURF_DIR" 2>/dev/null | sed 's|^|    |'

echo "═══ 2. REWRITE loadManifests → TEMPLATE-LITERAL DYNAMIC IMPORT ═══"
python3 - "$MACRO" "$SURF_DIR" << 'PY'
import pathlib, re, sys
macro = pathlib.Path(sys.argv[1])
surf = pathlib.Path(sys.argv[2])
src = macro.read_text()

# enumerate JSON basenames (build-time static list, but consumed dynamically)
names = sorted(p.stem for p in surf.glob("*.json"))
if not names:
    print(f"  FAIL: no json under {surf}")
    sys.exit(1)
print(f"  static names: {names}")

# the whole new block. Top-level await + template literal dynamic import.
# Bun's bundler statically resolves `./surface/${n}.json` into embedded blobs
# because `names` is a literal string[] — no runtime fs walk.
new_block = f'''// Generated by tau_dynamic_surface.sh — do not edit by hand.
// Static name list + template-literal dynamic import so Bun's bundler
// embeds every ./surface/*.json at compile time. No runtime fs walk.
const __SURFACE_NAMES = {repr(names)} as const;

const __SURFACE_MANIFESTS: SurfaceManifest[] = await Promise.all(
  __SURFACE_NAMES.map(async (n) =>
    ((await import(`./surface/${{n}}.json`)).default as SurfaceManifest)
  ),
);

export function loadManifests(): SurfaceManifest[] {{
  return __SURFACE_MANIFESTS;
}}
'''

# find the whole old loadManifests function and its preceding SURFACE_DIR decl if present
old_fn = re.compile(
    r'(?:const\s+SURFACE_DIR[^;]*;\s*\n)?'
    r'export\s+function\s+loadManifests\s*\(\s*\)\s*:\s*SurfaceManifest\[\]\s*\{.*?\n\}',
    re.DOTALL,
)
src2, n = old_fn.subn(new_block, src)
if n == 0:
    # fallback: try just the function without the SURFACE_DIR prefix
    src2, n = re.subn(
        r'export\s+function\s+loadManifests\s*\(\s*\)\s*:\s*SurfaceManifest\[\]\s*\{.*?\n\}',
        new_block, src, flags=re.DOTALL)
if n == 0:
    print("  FAIL: could not match loadManifests — dumping header")
    print("\n".join(src.splitlines()[:40]))
    sys.exit(1)
print(f"  replaced loadManifests ({n} site)")

# drop now-unused node:fs / node:path imports only if nothing else uses them
for sym in ("readdirSync", "readFileSync", "readSync"):
    if not re.search(rf'(?<![.\w]){sym}\s*\(', src2):
        src2 = re.sub(rf'import\s*\{{[^}}]*\b{sym}\b[^}}]*\}}\s*from\s*"node:fs";\s*\n', "", src2)
if not re.search(r'(?<![.\w])join\s*\(', src2) and 'path.join(' not in src2:
    src2 = re.sub(r'import\s*\{[^}]*\bjoin\b[^}]*\}\s*from\s*"node:path";\s*\n', "", src2)
if not re.search(r'(?<![.\w])resolve\s*\(', src2) and 'path.resolve(' not in src2:
    src2 = re.sub(r'import\s*\{[^}]*\bresolve\b[^}]*\}\s*from\s*"node:path";\s*\n', "", src2)

macro.write_text(src2)
print(f"  wrote {macro}")
PY

echo "═══ 3. INSPECT THE NEW BLOCK ═══"
sed -n '/__SURFACE_NAMES/,/^}/p' "$MACRO" | head -25 | sed 's|^|    |'

echo "═══ 4. SANITY: no readdirSync of surface, no fs reads ═══"
if grep -qE 'readdirSync|SURFACE_DIR' "$MACRO"; then
  echo "  WARN: readdirSync/SURFACE_DIR still present — pasting context"
  grep -nE 'readdirSync|SURFACE_DIR|loadManifests' "$MACRO" | sed 's|^|    |'
else
  echo "  OK: no runtime fs walk of surface/"
fi

echo "═══ 5. REBUILD ═══"
[ -x "$BIN" ] && cp "$BIN" "$BIN.bak.$STAMP"
cd "$TAU" || exit 1
if bun run build 2>&1 | tail -25; then
  for c in packages/coding-agent/dist/tau dist/tau bin/tau; do
    if [ -f "$c" ]; then
      cp "$c" "$BIN.new" && mv "$BIN.new" "$BIN" && chmod +x "$BIN"
      echo "  installed: $c"
      break
    fi
  done
else
  echo "  BUILD FAILED"
  [ -f "$BIN.bak.$STAMP" ] && cp "$BIN.bak.$STAMP" "$BIN" && echo "  rolled back binary"
  exit 1
fi

echo "═══ 6. SMOKE ═══"
S="/tmp/tau_smoke_dyn_$STAMP.log"
if timeout 60 tau -p "reply with only: ok" > "$S" 2>&1; then
  if grep -qiE '(^|\s)ok(\s|$)' "$S"; then
    echo "  SMOKE OK"
  else
    echo "  SMOKE: ran, no 'ok'"
    tail -15 "$S" | sed 's|^|    |'
  fi
else
  echo "  SMOKE FAIL"
  tail -25 "$S" | sed 's|^|    |'
fi
echo
echo "  smoke:  $S"
echo "  binary: $BIN  (backup $BIN.bak.$STAMP)"
